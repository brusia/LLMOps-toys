import re
import pandas as pd

def clean_text(text: str) -> str:
    """
    Очистка и нормализация русскоязычного текста
    
    :param text: Входной текст для очистки
    :return: Очищенный и нормализованный текст
    """
    if not isinstance(text, str):
        return ""
    
    # Убираем эмодзи и специальные символы, оставляем только буквы, цифры и пробелы
    cleaned = re.sub(r'[^\w\sа-яА-ЯёЁ]', '', text, flags=re.UNICODE)
    
    # Нормализуем пробелы (заменяем множественные пробелы на один)
    cleaned = re.sub(r'\s+', ' ', cleaned)
    
    # Убираем ведущие и завершающие пробелы
    cleaned = cleaned.strip()
    
    # Нормализуем регистр (делаем первую букву заглавной, остальные строчными)
    if cleaned:
        cleaned = cleaned[0].upper() + cleaned[1:].lower()
    
    # Убираем повторяющиеся знаки препинания (оставляем по одному)
    cleaned = re.sub(r'([.!?])\1+', r'\1', cleaned)
    
    # Разделяем слитно написанные слова (например, iPhone14)
    # Добавляем пробел между буквами и цифрами
    cleaned = re.sub(r'([a-zA-Z])([0-9])', r'\1 \2', cleaned)
    cleaned = re.sub(r'([0-9])([a-zA-Z])', r'\1 \2', cleaned)
    
    return cleaned


